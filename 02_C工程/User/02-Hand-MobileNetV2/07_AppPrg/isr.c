//===========================================================================
// 函数名称：SecAdd1
// 函数返回：无
// 参数说明：*p:为指向一个时分秒数组p[3]，p[2],秒；p[1],分，p[0],时
// 功能概要：秒单元+1，并处理时分单元（00:00:00-23:59:59)
//===========================================================================
void SecAdd1(uint8_t *p)
{
	// 【1】秒+1
	*(p + 2) += 1;
	// 【2】未到60秒，退出；到则清秒，分+1
	if (*(p + 2) < 60)
		goto SecAdd1_exit; // 使用goto向后跳，减少{}嵌套
	*(p + 2) = 0;		   // 到60秒，清秒，分+1
	*(p + 1) += 1;
	// 【3】未到60分，退出；到则清分，时+1
	if (*(p + 1) < 60)
		goto SecAdd1_exit;
	*(p + 1) = 0; // 到60分，清分，时+1
	*p += 1;
	// 【4】未到24时，退出；到则清时
	if (*p < 24)
		goto SecAdd1_exit;
	*p = 0; // 清时
SecAdd1_exit:
	__asm("nop");
}

