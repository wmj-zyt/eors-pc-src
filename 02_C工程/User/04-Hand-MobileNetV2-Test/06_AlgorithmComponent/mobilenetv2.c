//=====================================================================
//函数名称：Model_PredictImage
//函数返回：无
//参数说明：result：保存推理结果
//功能概要：模型推理函数
//=====================================================================
void Model_PredictImage(float *result)
{
    clear();

    CONV2D(g_modelInputImage, conv2d, conv2d_kernel, conv2d_bias, 2, "same");

    BATCH_NORMALIZATION(conv2d, batch_normalization_params);

    ACTIVATION(conv2d, relu6);

    CONV2D(conv2d, conv2d_1, conv2d_1_kernel, conv2d_1_bias, 1, "same");

    BATCH_NORMALIZATION(conv2d_1, batch_normalization_1_params);

    ACTIVATION(conv2d_1, relu6);

    DEPTHWISE_CONV2D(conv2d_1, depthwise_conv2d, depthwise_conv2d_depthwise_kernel,depthwise_conv2d_bias, 2);

    BATCH_NORMALIZATION(depthwise_conv2d, batch_normalization_2_params);

    ACTIVATION(depthwise_conv2d, relu6);

    CONV2D(depthwise_conv2d, conv2d_2, conv2d_2_kernel, conv2d_2_bias, 1, "same");

    BATCH_NORMALIZATION(conv2d_2, batch_normalization_3_params);

    CONV2D(conv2d_2, conv2d_3, conv2d_3_kernel, conv2d_3_bias, 1, "same");

    BATCH_NORMALIZATION(conv2d_3, batch_normalization_4_params);

    ACTIVATION(conv2d_3, relu6);

    DEPTHWISE_CONV2D(conv2d_3, depthwise_conv2d_1, depthwise_conv2d_1_depthwise_kernel,depthwise_conv2d_1_bias, 1);

    BATCH_NORMALIZATION(depthwise_conv2d_1, batch_normalization_5_params);

    ACTIVATION(depthwise_conv2d_1, relu6);

    CONV2D(depthwise_conv2d_1, conv2d_4, conv2d_4_kernel, conv2d_4_bias, 1, "same");

    BATCH_NORMALIZATION(conv2d_4, batch_normalization_6_params);

    ADD(conv2d_4, conv2d_2, add);

    CONV2D(add, conv2d_5, conv2d_5_kernel, conv2d_5_bias, 2, "same");

    BATCH_NORMALIZATION(conv2d_5, batch_normalization_7_params);

    ACTIVATION(conv2d_5, relu6);

    CONV2D(conv2d_5, conv2d_6, conv2d_6_kernel, conv2d_6_bias, 1, "same");

    BATCH_NORMALIZATION(conv2d_6, batch_normalization_8_params);

    ACTIVATION(conv2d_6, relu6);

    CONV2D(conv2d_6, conv2d_7, conv2d_7_kernel, conv2d_7_bias, 1, "same");

    BATCH_NORMALIZATION(conv2d_7, batch_normalization_9_params);

    ACTIVATION(conv2d_7, relu6);

    GLOBALAVERAGEPOOLING(conv2d_7, global_average_pooling2d);

    RESHAPE(global_average_pooling2d, reshape);

    CONV2D(reshape, conv2d_8, conv2d_8_kernel, conv2d_8_bias, 1, "same");

    SOFTMAX(conv2d_8);

    RESHAPE(conv2d_8, reshape_1);

    // 将结果赋值给result
    for (int i = 0; i < SortNum; i++)
    {
        result[i] = reshape_1[i];
    }
}

