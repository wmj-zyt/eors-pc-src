//=====================================================================
// 函数名称:relu6
// 函数返回:激活值
// 参数说明:x:待激活值
// 功能概要:将输出值限制在(0,6)之间
//=====================================================================
float relu6(float x)
{
    if (x <= 0)
        return 0;
    else if (x > 6)
        return 6;
    return x;
}

//=====================================================================
// 函数名称:softmax
// 函数返回:无
// 参数说明:input:输入数组指针, dim:数组维度
// 功能概要:Softmax激活函数，直接修改input数组
//=====================================================================
void softmax(float *input, int dim) {
    float max_val = input[0];
    float sum_exp = 0.0;

    // 找最大值，避免指数溢出
    for (int i = 1; i < dim; i++) {
        if (input[i] > max_val) {
            max_val = input[i];
        }
    }

    // 计算指数并求和
    for (int i = 0; i < dim; i++) {
        input[i] = expf(input[i] - max_val);
        sum_exp += input[i];
    }

    // 归一化输出
    for (int i = 0; i < dim; i++) {
        input[i] /= sum_exp;
    }
}

